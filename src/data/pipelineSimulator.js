export function simulateLiveEventPipeline(nodes, connections) {
  const steps = [];
  const logs = [];
  let isSuccessful = true;
  let failureReason = null;

  if (nodes.length === 0) {
    return {
      success: false,
      steps: [],
      logs: [{ step: 0, text: '❌ Pipeline Failed: Canvas is empty. Add architecture components.', time: '0ms', status: 'error' }],
      failureReason: 'No components on canvas'
    };
  }

  // Build adjacency graph
  const adj = {};
  nodes.forEach(n => { adj[n.id] = []; });
  connections.forEach(c => {
    if (adj[c.from]) adj[c.from].push(c.to);
  });

  const types = new Set(nodes.map(n => n.type));

  // Find Ingress Node (Client or Gateway)
  const clientNode = nodes.find(n => n.type === 'client');
  const gatewayNode = nodes.find(n => n.type === 'gateway' || n.type === 'graphql' || n.type === 'cdn');
  const springBootNode = nodes.find(n => n.type === 'springboot');
  const computeNode = springBootNode || nodes.find(n => n.type === 'nodejs' || n.type === 'fastapi' || n.type === 'lambda');
  const cacheNode = nodes.find(n => n.type === 'cache');
  const queueNode = nodes.find(n => n.type === 'queue');
  const dlqNode = nodes.find(n => n.type === 'dlq');
  const dbNode = nodes.find(n => n.type === 'postgres' || n.type === 'dynamodb');

  // STEP 1: Inbound Event Arrival
  if (clientNode) {
    steps.push({ step: 1, activeNodeId: clientNode.id, title: 'Event Generated', desc: 'Trigger event created at client/webhook' });
    logs.push({ step: 1, text: `📥 [STAGE 1 - EVENT RECEIVED]: Inbound event generated by "${clientNode.label}".`, time: '0ms', status: 'ok' });
  } else if (gatewayNode) {
    steps.push({ step: 1, activeNodeId: gatewayNode.id, title: 'Event Ingested', desc: 'Direct webhook arrived at API Gateway' });
    logs.push({ step: 1, text: `📥 [STAGE 1 - EVENT RECEIVED]: Inbound event received at "${gatewayNode.label}".`, time: '0ms', status: 'ok' });
  } else {
    return {
      success: false,
      steps: [],
      logs: [{ step: 1, text: '❌ Pipeline Failed: Missing Inbound Event Source. Add a "Client" or "API Gateway" component.', time: '0ms', status: 'error' }],
      failureReason: 'No entry point / client node'
    };
  }

  // Check connection from Client -> Gateway/Compute
  if (clientNode && gatewayNode) {
    const connected = (adj[clientNode.id] || []).includes(gatewayNode.id);
    if (!connected) {
      logs.push({ step: 1, text: `⚠️ Warning: "${clientNode.label}" is not connected to "${gatewayNode.label}". Traversal may bypass API Gateway!`, time: '+4ms', status: 'warn' });
    }
  }

  // STEP 2: In-Memory Cache Read
  if (cacheNode) {
    // Check if compute is connected to cache
    const computeConnectedToCache = computeNode && (
      (adj[computeNode.id] || []).includes(cacheNode.id) || 
      (adj[cacheNode.id] || []).includes(computeNode.id)
    );

    steps.push({ step: 2, activeNodeId: cacheNode.id, title: 'In-Memory Cache Read', desc: 'Querying Redis/Caffeine for templates & recipient preferences' });
    if (computeConnectedToCache) {
      logs.push({ step: 2, text: `⚡ [STAGE 2 - CACHE QUERY]: "${computeNode.label}" queried "${cacheNode.label}". In-memory lookup: Cache Hit in 0.6ms.`, time: '+11ms', status: 'ok' });
    } else {
      logs.push({ step: 2, text: `⚡ [STAGE 2 - CACHE QUERY]: "${cacheNode.label}" exists. (Note: Connect with compute arrow for optimal graph topology).`, time: '+11ms', status: 'ok' });
    }
  } else if (dbNode) {
    steps.push({ step: 2, activeNodeId: dbNode.id, title: 'Slow Disk DB Read', desc: 'Querying relational/NoSQL disk storage' });
    logs.push({ step: 2, text: `⚠️ [STAGE 2 - DISK DB QUERY]: In-Memory Cache MISSING! Fetched from "${dbNode.label}" via disk I/O (Latency: 28.4ms). Add In-Memory Cache (Redis) to accelerate.`, time: '+28ms', status: 'warn' });
  } else {
    logs.push({ step: 2, text: '⚠️ [STAGE 2 - CACHE SKIPPED]: No In-Memory Cache or Database found on canvas. Hardcoded template fallback used.', time: '+5ms', status: 'warn' });
  }

  // STEP 3: Business Logic Processing
  if (computeNode) {
    steps.push({ step: 3, activeNodeId: computeNode.id, title: 'Processing Done', desc: 'Executing business validation & template formatting' });
    logs.push({ step: 3, text: `⚙️ [STAGE 3 - PROCESSING DONE]: "${computeNode.label}" compiled payload, checked rate limits (PASS), and evaluated deduplication hash.`, time: '+19ms', status: 'ok' });
  } else {
    return {
      success: false,
      steps,
      logs: [
        ...logs,
        { step: 3, text: '❌ Pipeline Broken: Missing Compute Service. Add "Java Spring Boot" or another backend worker to process the event.', time: '+15ms', status: 'error' }
      ],
      failureReason: 'Missing compute engine'
    };
  }

  // STEP 4: Event Sent Out
  if (queueNode) {
    steps.push({ step: 4, activeNodeId: queueNode.id, title: 'Event Sent Out', desc: 'Outbound event bus published' });
    logs.push({ step: 4, text: `🚀 [STAGE 4 - EVENT SENT OUT]: Event published to "${queueNode.label}". Multi-channel consumer workers notified.`, time: '+32ms', status: 'ok' });

    if (dlqNode) {
      steps.push({ step: 4, activeNodeId: dlqNode.id, title: 'DLQ Attached', desc: 'Fault isolation enabled' });
      logs.push({ step: 4, text: `🛡️ [FAULT ISOLATION]: "${dlqNode.label}" is active to catch poisoned messages and failed deliveries.`, time: '+35ms', status: 'ok' });
    } else {
      logs.push({ step: 4, text: '⚠️ Warning: Missing Dead Letter Queue (DLQ). Failed delivery retries risk message loss.', time: '+35ms', status: 'warn' });
    }
  } else {
    // Synchronous fallback
    logs.push({ step: 4, text: '⚠️ [STAGE 4 - DIRECT SYNC DISPATCH]: Outbound Event Bus missing. Sent synchronously. High traffic bursts may exhaust connection pool.', time: '+45ms', status: 'warn' });
    steps.push({ step: 4, activeNodeId: computeNode.id, title: 'Synchronous Sent', desc: 'Direct HTTP dispatch' });
  }

  return {
    success: true,
    steps,
    logs,
    failureReason: null
  };
}
